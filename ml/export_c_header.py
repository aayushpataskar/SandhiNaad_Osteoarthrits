#!/usr/bin/env python3
"""
SandhiNaad — Export trained logistic regression to a C header for the ESP32.

Reads the saved scaler and model (joblib), writes ``firmware/SandhiNaad/model.h``
with inline arrays for feature means, stds, coefficients, intercept, and
threshold, plus an inline ``model_predict()`` function.

Also prints a test-vector verification so the caller can confirm that the
C output matches the Python prediction within 1e-4.

Usage:
    python export_c_header.py \\
        --model  ml/models/acoustic_model.joblib \\
        --scaler ml/models/acoustic_scaler.joblib \\
        --output ../firmware/SandhiNaad/model.h

    python export_c_header.py  (uses defaults)
"""

import argparse
import json
import os
import sys
import textwrap

import joblib
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from config import ACOUSTIC_FEATURES

# Standardised features are clipped to +-Z_CLIP (host model.py does the same)
Z_CLIP = 3.0


def _float_array_literal(arr, name: str, per_line: int = 4) -> str:
    """Format a float array as a C static const initialiser."""
    lines = [f'static const float {name}[MODEL_NUM_FEATURES] = {{']
    vals = [f'{v:.10e}f' for v in arr]
    for i in range(0, len(vals), per_line):
        chunk = ', '.join(vals[i:i + per_line])
        suffix = ',' if i + per_line < len(vals) else ''
        lines.append(f'    {chunk}{suffix}')
    lines.append('};')
    return '\n'.join(lines)


def export(model_path: str, scaler_path: str, output_path: str,
           info_path: str | None = None) -> None:
    """Write the C header file."""
    model = joblib.load(model_path)
    scaler = joblib.load(scaler_path)

    means = scaler.mean_
    stds = scaler.scale_
    coefs = model.coef_[0]
    intercept = float(model.intercept_[0])

    # Load threshold from model_info.json if available
    threshold = 0.5
    if info_path and os.path.exists(info_path):
        with open(info_path) as f:
            info = json.load(f)
            threshold = info.get('threshold', 0.5)
    else:
        # Try to find model_info.json next to the model
        candidate = os.path.join(os.path.dirname(model_path), 'model_info.json')
        if os.path.exists(candidate):
            with open(candidate) as f:
                info = json.load(f)
                threshold = info.get('threshold', 0.5)

    n_feat = len(ACOUSTIC_FEATURES)
    assert len(means) == n_feat, f'Scaler has {len(means)} features, expected {n_feat}'
    assert len(coefs) == n_feat, f'Model has {len(coefs)} coefficients, expected {n_feat}'

    # ── Test vector ────────────────────────────────────────────────────────
    rng = np.random.default_rng(99)
    # A plausible feature row: mean + N(0,1)*std per feature
    test_vec = means + rng.normal(0, 1, size=n_feat) * stds
    # Compute expected output in Python
    z_std = np.clip((test_vec - means) / (stds + 1e-8), -Z_CLIP, Z_CLIP)
    logit = float(np.dot(coefs, z_std) + intercept)
    prob = 1.0 / (1.0 + np.exp(-logit))

    # ── Build header ───────────────────────────────────────────────────────
    feature_names_str = ', '.join(f'"{f}"' for f in ACOUSTIC_FEATURES)
    test_vec_str = ', '.join(f'{v:.10e}f' for v in test_vec)

    header = textwrap.dedent("""\
    /*
     * model.h — Auto-generated by export_c_header.py
     *
     * Logistic regression model for knee-OA screening.
     * TRAINED ON SYNTHETIC DATA — demonstration only, not clinically validated.
     *
     * Feature order must match ACOUSTIC_FEATURES in ml/config.py.
     *
     * Test vector verification:
     *   Input:    see MODEL_TEST_VECTOR below
     *   Expected: probability = {prob:.10f}
     *   Logit:    {logit:.10f}
     *   The firmware and host predictions must agree within 1e-4.
     */

    #ifndef MODEL_H
    #define MODEL_H

    #include <math.h>

    #define MODEL_NUM_FEATURES {n_feat}
    #define MODEL_SYNTHETIC    1  /* trained on synthetic data */
    #define MODEL_Z_CLIP       {z_clip:.1f}f

    static const char* MODEL_FEATURE_NAMES[MODEL_NUM_FEATURES] = {{
        {feature_names_str}
    }};

    {means_arr}

    {stds_arr}

    {coefs_arr}

    static const float MODEL_INTERCEPT = {intercept:.10e}f;
    static const float MODEL_THRESHOLD = {threshold:.10e}f;

    /* Test vector for verification (see comment at top for expected output) */
    static const float MODEL_TEST_VECTOR[MODEL_NUM_FEATURES] = {{
        {test_vec_str}
    }};
    static const float MODEL_TEST_EXPECTED_PROB = {prob:.10e}f;

    /**
     * Compute OA-risk probability from acoustic features.
     *
     * @param features  Array of MODEL_NUM_FEATURES floats in the order
     *                  defined by MODEL_FEATURE_NAMES.
     * @return          Probability in [0, 1].
     */
    static inline float model_predict(const float* features) {{
        float z = MODEL_INTERCEPT;
        for (int i = 0; i < MODEL_NUM_FEATURES; i++) {{
            float std_val = (features[i] - MODEL_MEAN[i]) / (MODEL_STD[i] + 1e-8f);
            if (std_val >  MODEL_Z_CLIP) std_val =  MODEL_Z_CLIP;
            if (std_val < -MODEL_Z_CLIP) std_val = -MODEL_Z_CLIP;
            z += MODEL_COEF[i] * std_val;
        }}
        return 1.0f / (1.0f + expf(-z));
    }}

    /**
     * Classify: returns 1 if probability >= threshold, else 0.
     */
    static inline int model_classify(const float* features) {{
        return model_predict(features) >= MODEL_THRESHOLD ? 1 : 0;
    }}

    #endif /* MODEL_H */
    """).format(prob=prob, logit=logit, n_feat=n_feat,
                feature_names_str=feature_names_str,
                means_arr=_float_array_literal(means, 'MODEL_MEAN'),
                stds_arr=_float_array_literal(stds, 'MODEL_STD'),
                coefs_arr=_float_array_literal(coefs, 'MODEL_COEF'),
                intercept=intercept, threshold=threshold,
                test_vec_str=test_vec_str, z_clip=Z_CLIP)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', newline='\n', encoding='utf-8') as f:
        f.write(header)

    print(f'Exported model to {output_path}')
    print(f'  Features:    {n_feat}')
    print(f'  Intercept:   {intercept:.6f}')
    print(f'  Threshold:   {threshold:.6f}')
    print(f'  Test vector: prob = {prob:.6f}  (logit = {logit:.6f})')
    print()
    print('Verification — Python prediction on test vector:')
    print(f'  Probability: {prob:.10f}')
    print(f'  Class:       {"OA" if prob >= threshold else "Control"}')
    print(f'  The C model_predict() on MODEL_TEST_VECTOR should return {prob:.10f} ± 1e-4')


def main() -> None:
    parser = argparse.ArgumentParser(
        description='Export trained model to C header for ESP32 firmware.')
    parser.add_argument('--model', type=str,
                        default=os.path.join(os.path.dirname(__file__),
                                             'models', 'acoustic_model.joblib'),
                        help='Path to saved LogisticRegression joblib')
    parser.add_argument('--scaler', type=str,
                        default=os.path.join(os.path.dirname(__file__),
                                             'models', 'acoustic_scaler.joblib'),
                        help='Path to saved StandardScaler joblib')
    parser.add_argument('--info', type=str, default=None,
                        help='Path to model_info.json (for threshold)')
    parser.add_argument('--output', type=str,
                        default=os.path.join(os.path.dirname(__file__),
                                             '..', 'firmware', 'SandhiNaad', 'model.h'),
                        help='Output C header path')
    args = parser.parse_args()

    export(args.model, args.scaler, args.output, args.info)


if __name__ == '__main__':
    main()
